'use strict';
// Loom — long-lived shell sessions.
// Each branch of cards owns one interactive shell in a PTY. Commands are
// sourced from temp scripts at the top level of that shell, so `export`, `cd`,
// `source .venv/bin/activate` and friends carry over to the next card. Shell
// integration hooks mark up the PTY stream (OSC 133, like iTerm2/Warp/VS Code)
// and the parser below cuts each command's output back out of it.

const path = require('path');
const fs = require('fs');
const os = require('os');
const crypto = require('crypto');
const { execFile } = require('child_process');

const MAX_OUTPUT = 5 * 1024 * 1024; // per command
const MAX_OSC = 4096; // an escape sequence longer than this isn't one of ours
const MAX_SESSIONS = 12;
const STARTUP_MS = 30000;
const READY_MS = 150; // themes can rewrite the prompt and lose 133;B

const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

function isDir(p) {
  try { return fs.statSync(p).isDirectory(); } catch { return false; }
}

// ---------------------------------------------------------------- shell integration
// Every marker carries a per-session nonce that only the hooks know (it's an
// unexported shell variable). Without it, `cat` of a hostile file could forge
// a finished command, or point LoomEnv at a file that Loom would later source.
const AFTER_RC = String.raw`
if [ -r "$__LOOM_RESTORE" ]; then . "$__LOOM_RESTORE"; fi 2>/dev/null
export PAGER=cat GIT_PAGER=cat
if [ -n "$__LOOM_CWD" ]; then \builtin cd -- "$__LOOM_CWD"; fi
unset __LOOM_RESTORE __LOOM_CWD
`;

// The typed line ends with __loom_d, so 133;D lands before anything the shell
// or a theme prints ahead of the next prompt. The prompt hook is the backstop
// for when ^C aborts that line.
// A DEBUG trap is bash's usual stand-in for preexec, but it fights user traps.
// Loom types every line itself, so the line can call __loom_c directly.
// The rc files are sourced here and not in a function, where `declare` is local.
const BASH_RC = String.raw`# Generated by Loom.
if [ "$__LOOM_LOGIN" = 1 ]; then
  if [ -r /etc/profile ]; then . /etc/profile; fi
  __loom_p=
  for __loom_f in ~/.bash_profile ~/.bash_login ~/.profile; do
    if [ -r "$__loom_f" ]; then __loom_p=$__loom_f; break; fi
  done
  if [ -n "$__loom_p" ]; then . "$__loom_p"; fi
  if [ -r ~/.bashrc ] && { [ -z "$__loom_p" ] || ! grep -q bashrc "$__loom_p"; }; then . ~/.bashrc; fi
  unset __loom_p __loom_f
elif [ -r ~/.bashrc ]; then . ~/.bashrc
fi

__loom_nonce=$__LOOM_NONCE
__loom_snap=$__LOOM_SNAP
__loom_b="\[\033]133;B;loom=$__loom_nonce\007\]"
__loom_armed=0
__loom_ec=0
unset __LOOM_NONCE __LOOM_SNAP __LOOM_LOGIN
set +o history
unset HISTFILE

__loom_c() {
  local ec=$__loom_ec
  __loom_armed=1
  \builtin printf '\033]133;C;loom=%s\007' "$__loom_nonce"
  return $ec
}
__loom_end() {
  \builtin printf '\033]133;D;%s;loom=%s\007' "$1" "$__loom_nonce"
  \builtin printf '\033]7;file://%s%s\007' "$HOSTNAME" "${"$"}{PWD//\%/%25}"
  __loom_armed=0
  \builtin export -p >| "$__loom_snap" 2>/dev/null
  \builtin printf '\033]1337;LoomEnv=%s;loom=%s\007' "$__loom_snap" "$__loom_nonce"
}
__loom_d() {
  local ec=$?
  __loom_end "$ec"
  return $ec
}
__loom_pre() {
  local ec=$?
  __loom_ec=$ec
  if [ "$__loom_armed" = 1 ]; then __loom_end "$ec"; fi
  return $ec
}
__loom_post() {
  local ec=$?
  PS1=${"$"}{PS1%"$__loom_b"}$__loom_b
  \builtin printf '\033]133;A;loom=%s\007' "$__loom_nonce"
  return $ec
}
__loom_pc=$(IFS=$'\n'; \builtin printf '%s' "${"$"}{PROMPT_COMMAND[*]-}")
unset PROMPT_COMMAND
PROMPT_COMMAND=__loom_pre$'\n'$__loom_pc$'\n'__loom_post
unset __loom_pc
${AFTER_RC}`;

const ZSH_HOOKS = String.raw`
typeset -g __loom_nonce=$__LOOM_NONCE __loom_snap=$__LOOM_SNAP __loom_armed=0
typeset -g __loom_b=$'%{\e]133;B;loom='$__loom_nonce$'\a%}'
unset __LOOM_NONCE __LOOM_SNAP HISTFILE

__loom_preexec() {
  __loom_armed=1
  \builtin printf '\033]133;C;loom=%s\007' "$__loom_nonce"
}
__loom_end() {
  emulate -L zsh
  \builtin printf '\033]133;D;%s;loom=%s\007' "$1" "$__loom_nonce"
  \builtin printf '\033]7;file://%s%s\007' "$HOST" "${"$"}{PWD//\%/%25}"
  __loom_armed=0
  \builtin typeset -px >| "$__loom_snap" 2>/dev/null
  \builtin printf '\033]1337;LoomEnv=%s;loom=%s\007' "$__loom_snap" "$__loom_nonce"
}
__loom_d() {
  local ec=$?
  __loom_end $ec
  return $ec
}
__loom_precmd_first() {
  local ec=$?
  if (( __loom_armed )); then __loom_end $ec; fi
  return $ec
}
__loom_precmd_last() {
  local ec=$?
  PROMPT=${"$"}{PROMPT%"$__loom_b"}$__loom_b
  \builtin printf '\033]133;A;loom=%s\007' "$__loom_nonce"
  return $ec
}
# zsh prints PROMPT_SP and calls a plain precmd() before precmd_functions. When
# ^C skips __loom_d, those would land inside the card.
unsetopt prompt_sp
typeset -ga precmd_functions preexec_functions
if (( $+functions[precmd] )); then
  functions[__loom_user_precmd]=$functions[precmd]
  unfunction precmd
  precmd_functions=(__loom_user_precmd $precmd_functions)
fi
precmd_functions=(__loom_precmd_first $precmd_functions __loom_precmd_last)
preexec_functions+=(__loom_preexec)
`;

// Each stage runs the user's file with ZDOTDIR pointing at their real config
// (a .zshenv may change it), then points it back here so zsh finds our next
// stage. .zlogin is the last stage of a login shell, so it finishes the job.
const zshStage = (name, tail = '') => String.raw`# Generated by Loom.
__loom_zd=$ZDOTDIR
ZDOTDIR=$__LOOM_USER_ZDOTDIR
if [[ -r $ZDOTDIR/${name} ]]; then builtin source "$ZDOTDIR/${name}"; fi
__LOOM_USER_ZDOTDIR=$ZDOTDIR
ZDOTDIR=$__loom_zd
unset __loom_zd
${tail}`;

const ZSH_LOGIN_TAIL = String.raw`
if [[ $__LOOM_USER_ZDOTDIR == $HOME ]]; then unset ZDOTDIR; else export ZDOTDIR=$__LOOM_USER_ZDOTDIR; fi
unset __LOOM_USER_ZDOTDIR
${AFTER_RC}`;

function writeIntegration(dir) {
  const zdot = path.join(dir, 'zdot');
  fs.mkdirSync(zdot);
  fs.writeFileSync(path.join(dir, 'bashrc'), BASH_RC);
  fs.writeFileSync(path.join(zdot, '.zshenv'), zshStage('.zshenv'));
  fs.writeFileSync(path.join(zdot, '.zprofile'), zshStage('.zprofile'));
  fs.writeFileSync(path.join(zdot, '.zshrc'), zshStage('.zshrc', ZSH_HOOKS));
  fs.writeFileSync(path.join(zdot, '.zlogin'), zshStage('.zlogin', ZSH_LOGIN_TAIL));
}

function shellLaunch(kind, dir) {
  if (kind === 'zsh') {
    return {
      args: ['-l', '-i'],
      env: { ZDOTDIR: path.join(dir, 'zdot'), __LOOM_USER_ZDOTDIR: process.env.ZDOTDIR || os.homedir() },
      line: (script, stdin) => ` \\builtin source ${shq(script)}${stdin ? ` < ${shq(stdin)}` : ''};__loom_d`,
    };
  }
  return {
    // bash ignores --rcfile in a login shell, so the rcfile plays that part.
    // macOS terminals open login shells; Linux ones usually don't.
    args: ['--rcfile', path.join(dir, 'bashrc'), '-i'],
    env: { __LOOM_LOGIN: process.platform === 'darwin' ? '1' : '0', BASH_SILENCE_DEPRECATION_WARNING: '1' },
    line: (script, stdin) => ` __loom_c;\\builtin source ${shq(script)}${stdin ? ` < ${shq(stdin)}` : ''};__loom_d`,
  };
}

// ---------------------------------------------------------------- stream parser
// Splits PTY text on the markers above. Only text between C and D is reported
// as output, which is what keeps prompts and the echoed command off the card.
function createParser(nonce, on) {
  const tag = `loom=${nonce}`;
  let held = '';
  let inOutput = false;

  function marker(body) {
    let m = /^133;([ABC]);(.*)$/s.exec(body);
    if (m && m[2] === tag) {
      if (m[1] === 'C') { inOutput = true; on.outputStart(); }
      else if (m[1] === 'A') { inOutput = false; on.promptStart(); }
      else on.promptEnd();
      return true;
    }
    m = /^133;D;(-?\d+);(.*)$/s.exec(body);
    if (m && m[2] === tag) {
      inOutput = false;
      on.finish(Number(m[1]));
      return true;
    }
    m = /^1337;LoomEnv=(.*);(loom=[0-9a-f]+)$/s.exec(body);
    if (m && m[2] === tag) { on.env(m[1]); return true; }
    // A command's own OSC 7 is just output; ours and the prompt's come after D.
    m = !inOutput && /^7;file:\/\/[^/]*(\/.*)$/s.exec(body);
    if (m) {
      try { on.cwd(decodeURIComponent(m[1])); } catch { /* not percent-encoded */ }
      return true;
    }
    return false;
  }

  const emit = (text) => { if (inOutput && text) on.output(text); };

  function feed(chunk) {
    const s = held + chunk;
    held = '';
    let pos = 0; // start of text not yet emitted
    let scan = 0;
    for (;;) {
      const e = s.indexOf('\x1b', scan);
      if (e < 0) { emit(s.slice(pos)); return; }
      if (e === s.length - 1) { emit(s.slice(pos, e)); held = s.slice(e); return; }
      if (s[e + 1] !== ']') { scan = e + 1; continue; }
      // Find BEL or ST. Any other ESC aborts the OSC, as it does in xterm, so
      // garbage output can't swallow the real end-of-command marker after it.
      let end = -1;
      let width = 1;
      let aborted = -1;
      let partial = false;
      for (let j = e + 2; j < s.length; j++) {
        const c = s.charCodeAt(j);
        if (c === 7) { end = j; break; }
        if (c !== 0x1b) continue;
        if (j === s.length - 1) partial = true;
        else if (s[j + 1] === '\\') { end = j; width = 2; }
        else aborted = j;
        break;
      }
      if (aborted >= 0) { scan = aborted; continue; }
      if (end < 0) {
        if (s.length - e > MAX_OSC && !partial) { scan = e + 2; continue; }
        emit(s.slice(pos, e));
        held = s.slice(e);
        return;
      }
      const body = s.slice(e + 2, end);
      scan = end + width;
      const before = s.slice(pos, e);
      const textWasOutput = inOutput;
      if (marker(body)) {
        if (textWasOutput && before) on.output(before);
        pos = scan;
      }
    }
  }
  return { feed };
}

// ---------------------------------------------------------------- sessions
// `pty` is node-pty. `onData(id, chunks)` and `onExit(msg)` keep the IPC shape;
// `fallback(req)` runs a command that a shell couldn't be started for.
function createSessions({ pty, shell, env, envDir, onData, onExit, fallback, maxSessions = MAX_SESSIONS, startupMs = STARTUP_MS }) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'loom-'));
  writeIntegration(dir);
  fs.mkdirSync(envDir, { recursive: true, mode: 0o700 });
  const launch = shellLaunch(path.basename(shell), dir);
  const live = new Set();
  const cards = new Map(); // running card id -> card
  const size = { cols: 120, rows: 40 };
  let seq = 0;

  const rm = (p) => { if (p) fs.rm(p, { force: true }, () => {}); };

  function dispose(s) {
    live.delete(s);
    s.disposed = true;
    clearTimeout(s.startTimer);
    clearTimeout(s.readyTimer);
    try { s.pty.kill(); } catch { /* already gone */ }
    rm(s.snap);
  }

  function evictIdle() {
    let oldest = null;
    for (const s of live) if (!s.card && (!oldest || s.usedAt < oldest.usedAt)) oldest = s;
    if (oldest) dispose(oldest);
    return !!oldest;
  }

  function detach(s) {
    const c = s.card;
    s.card = null;
    cards.delete(c.id);
    for (const t of c.timers) clearTimeout(t);
    clearTimeout(c.flushTimer);
    rm(c.script);
    rm(c.stdinFile);
    return c;
  }

  function flush(c) {
    clearTimeout(c.flushTimer);
    c.flushTimer = null;
    if (c.text) { onData(c.id, [[0, c.text]]); c.text = ''; }
  }

  function push(c, chunk) {
    if (c.truncated) return;
    c.bytes += chunk.length;
    let text;
    if (c.bytes > MAX_OUTPUT) {
      c.truncated = true;
      text = `\n[loom: output truncated after ${MAX_OUTPUT / 1048576} MB]\n`;
    } else {
      // The PTY's ONLCR turns \n into \r\n, split across reads at any point.
      text = c.cr + chunk;
      const m = /\r+$/.exec(text);
      c.cr = m ? m[0] : '';
      if (m) text = text.slice(0, m.index);
      // Shell errors name the temp script, which means nothing on a card.
      text = text.replace(/\r+\n/g, '\n').split(c.script).join('loom');
    }
    c.text += text;
    if (!c.flushTimer) c.flushTimer = setTimeout(() => flush(c), 24);
  }

  function finish(s, code, { signal = null, envFile = null } = {}) {
    if (!s.card) return;
    const c = s.card;
    flush(c);
    detach(s);
    s.usedAt = Date.now();
    onExit({ id: c.id, code, signal, cwd: s.cwd, truncated: c.truncated, envFile });
    while (live.size > maxSessions && evictIdle());
  }

  function saveSnapshot(s, id) {
    const out = path.join(envDir, `card-${id}.sh`);
    try {
      fs.copyFileSync(s.snap, out);
      fs.chmodSync(out, 0o600);
      return out;
    } catch { return null; }
  }

  function dispatch(s) {
    const c = s.card;
    if (!c || c.sent || !s.ready) return;
    c.sent = true;
    s.ready = false;
    s.pty.write(`${launch.line(c.script, c.stdinFile)}\r`);
  }

  function ready(s) {
    clearTimeout(s.readyTimer);
    clearTimeout(s.startTimer);
    s.sawPrompt = false;
    s.ready = true;
    dispatch(s);
  }

  function abandon(s, why) {
    if (!s.card) { dispose(s); return; }
    const { req } = detach(s);
    dispose(s);
    onData(req.id, [[1, `[loom: ${why}; running this card without a shell session]\n`]]);
    fallback(req);
  }

  function spawn(cwd, restore) {
    while (live.size >= maxSessions && evictIdle());
    const n = ++seq;
    const s = {
      nonce: crypto.randomBytes(16).toString('hex'),
      snap: path.join(dir, `env-${n}`),
      cwd, tip: null, card: null, ready: false, sawPrompt: false, disposed: false,
      usedAt: Date.now(), startTimer: null, readyTimer: null, pty: null, parser: null,
    };
    s.parser = createParser(s.nonce, {
      outputStart() {},
      output(text) { if (s.card) push(s.card, text); },
      finish(code) { if (s.card) s.card.code = code; },
      cwd(p) { if (isDir(p)) s.cwd = p; },
      env(p) {
        const c = s.card;
        if (c && c.sent && c.code != null && p === s.snap) finish(s, c.code, { envFile: saveSnapshot(s, c.id) });
      },
      promptStart() {
        // A prompt with no 133;D: ^C beat the command, or it never ran.
        if (s.card && s.card.sent) finish(s, s.card.code != null ? s.card.code : 130);
        s.sawPrompt = true;
        clearTimeout(s.readyTimer);
        s.readyTimer = setTimeout(() => ready(s), READY_MS);
      },
      promptEnd() { if (s.sawPrompt) ready(s); },
    });
    s.pty = pty.spawn(shell, launch.args, {
      name: 'xterm-256color',
      cols: size.cols,
      rows: size.rows,
      cwd,
      env: {
        ...env(), ...launch.env,
        __LOOM_NONCE: s.nonce, __LOOM_SNAP: s.snap, __LOOM_RESTORE: restore || '', __LOOM_CWD: cwd,
      },
    });
    s.pty.onData((d) => s.parser.feed(d));
    s.pty.onExit(({ exitCode, signal }) => {
      if (s.disposed) return;
      if (s.card && !s.card.sent) { abandon(s, 'the shell exited during startup'); return; }
      dispose(s);
      finish(s, exitCode, { signal: signal ? String(signal) : null });
    });
    s.startTimer = setTimeout(() => abandon(s, 'the shell never reached a prompt'), startupMs);
    live.add(s);
    return s;
  }

  // A path from the renderer is only ever a snapshot Loom wrote itself.
  function validSnapshot(p) {
    if (typeof p !== 'string') return null;
    const full = path.resolve(p);
    return path.dirname(full) === path.resolve(envDir) && fs.existsSync(full) ? full : null;
  }

  function reusable(req) {
    if (req.parentId == null || req.fork) return null;
    for (const s of live) if (s.tip === req.parentId && !s.card) return s;
    return null;
  }

  function run(req) {
    let s = reusable(req);
    if (!s) {
      const cwd = req.cwd && isDir(req.cwd) ? req.cwd : os.homedir();
      try { s = spawn(cwd, validSnapshot(req.envFile)); } catch (err) {
        onData(req.id, [[1, `[loom: ${err.message}; running this card without a shell session]\n`]]);
        return fallback(req);
      }
    }
    // A rerun moves the card to a new shell; the one it left can't be reached.
    for (const o of live) if (o !== s && o.tip === req.id) dispose(o);
    const n = `${req.id}-${++seq}`;
    const c = {
      id: req.id, req, session: s, sent: false, code: null, killed: false,
      script: path.join(dir, `run-${n}.sh`),
      stdinFile: typeof req.stdin === 'string' ? path.join(dir, `stdin-${n}`) : null,
      text: '', cr: '', bytes: 0, truncated: false, flushTimer: null, timers: [],
    };
    fs.writeFileSync(c.script, `${req.command}\n`, { mode: 0o600 });
    if (c.stdinFile) fs.writeFileSync(c.stdinFile, req.stdin, { mode: 0o600 });
    s.card = c;
    s.tip = req.id;
    s.usedAt = Date.now();
    cards.set(req.id, c);
    dispatch(s);
    return { pid: s.pty.pid };
  }

  function signalForeground(s, sig) {
    execFile('ps', ['-o', 'tpgid=', '-p', String(s.pty.pid)], (_err, out) => {
      const pgid = parseInt(out, 10);
      if (!(pgid > 1) || pgid === s.pty.pid) return; // never the shell itself
      try { process.kill(-pgid, sig); } catch { /* already gone */ }
    });
  }

  function kill(id) {
    const c = cards.get(id);
    if (!c) return false;
    const s = c.session;
    if (!c.sent) { dispose(s); finish(s, 130); return true; }
    s.pty.write('\x03');
    const later = (ms, fn) => c.timers.push(setTimeout(fn, ms));
    later(2000, () => signalForeground(s, 'SIGTERM'));
    later(3500, () => signalForeground(s, 'SIGKILL'));
    // Nothing left to signal, so the shell itself is stuck: give up on it.
    later(5000, () => { dispose(s); finish(s, 130); });
    return true;
  }

  function stdin(id, data, eof) {
    const c = cards.get(id);
    if (!c || !c.sent) return false;
    if (data) c.session.pty.write(data);
    if (eof) c.session.pty.write('\x04');
    return true;
  }

  function resize(cols, rows) {
    if (!(cols > 0 && rows > 0)) return;
    Object.assign(size, { cols, rows });
    for (const s of live) { try { s.pty.resize(cols, rows); } catch { /* exiting */ } }
  }

  // The card is gone. A session whose tip it was can never be reached again:
  // a new child of the card's parent must not see what the card did.
  function forget(id) {
    rm(path.join(envDir, `card-${id}.sh`));
    for (const s of [...live]) {
      if (s.tip !== id) continue;
      dispose(s);
      finish(s, 130);
    }
  }

  function shutdown() {
    for (const s of [...live]) dispose(s);
    try { fs.rmSync(dir, { recursive: true, force: true }); } catch { /* best effort */ }
  }

  return { run, kill, stdin, resize, forget, shutdown, owns: (id) => cards.has(id), liveCount: () => live.size };
}

module.exports = { createParser, createSessions, shq };
