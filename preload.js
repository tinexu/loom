'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch) => (arg) => ipcRenderer.invoke(ch, arg);

// The rich-view worker's port to main arrives here and is handed to the page,
// which transfers it to the worker.
ipcRenderer.on('worker-port', (e) => window.postMessage('loom-worker-port', '*', e.ports));

contextBridge.exposeInMainWorld('loom', {
  sys: invoke('sys:info'),
  run: invoke('cmd:run'),
  kill: invoke('cmd:kill'),
  stdin: invoke('cmd:stdin'),
  resize: invoke('cmd:resize'),
  ack: (arg) => ipcRenderer.send('cmd:ack', arg),
  forget: invoke('cmd:forget'),
  onData: (fn) => ipcRenderer.on('cmd:data', (_e, m) => fn(m)),
  onExit: (fn) => ipcRenderer.on('cmd:exit', (_e, m) => fn(m)),
  onCapped: (fn) => ipcRenderer.on('out:capped', (_e, m) => fn(m)),
  onEvicted: (fn) => ipcRenderer.on('out:evicted', (_e, m) => fn(m)),
  outSubscribe: invoke('out:subscribe'),
  outReplay: invoke('out:replay'),
  outInfo: invoke('out:info'),
  outView: invoke('out:view'),
  outRange: invoke('out:range'),
  outLocate: invoke('out:locate'),
  outHead: invoke('out:head'),
  outClip: invoke('out:clip'),
  outSearch: invoke('out:search'),
  outReplace: invoke('out:replace'),
  outCopy: invoke('out:copy'),
  copyText: invoke('clip:write'),
  outSave: invoke('out:save'),
  outOpen: invoke('out:open'),
  workerPort: invoke('worker:port'),
  names: invoke('fs:names'),
  openPath: invoke('fs:open'),
  ai: invoke('ai:complete'),
  shellInfo: invoke('shell:info'),
  complete: invoke('complete:run'),
  pathsExist: invoke('fs:exists'),
  historyLoad: invoke('history:load'),
  historyAdd: invoke('history:add'),
  historyOffer: invoke('history:offer'),
  historyImport: invoke('history:import'),
  getSettings: invoke('settings:get'),
  setSettings: invoke('settings:set'),
  loadSession: invoke('session:load'),
  saveSession: invoke('session:save'),
  patchSession: invoke('session:patch'),
  smokeDone: invoke('smoke:done'),
  smokeReport: invoke('smoke:report'),
  smokeKeys: invoke('smoke:keys'),
  smokeResize: invoke('smoke:resize'),
  smokePaste: invoke('smoke:paste'),
  smokeOut: invoke('smoke:out'),
  smokeClipboard: invoke('smoke:clipboard'),
  smokeCopy: invoke('smoke:copy'),
  benchMem: invoke('bench:mem'),
  benchReport: invoke('bench:report'),
});
